export function fieldLabel(field: string, locale: Locale) {
  return fields[field]?.[locale === 'en' ? 0 : 1] ?? field.replace(/([a-z])([A-Z])/g, '$1 $2').replace(/^./, char => char.toUpperCase())
}

export function codeLabel(code: string, locale: Locale) {
  return codes[code]?.[locale === 'en' ? 0 : 1] ?? code
}
